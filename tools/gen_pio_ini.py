#!/usr/bin/env python3
"""Write a platformio.ini into every ESP32 firmware folder of the portfolio (flat lib/ + src/ layout), so each builds with
`pio run` exactly like the arduino-cli script tools/esp32_build.sh. Library-only projects get a tiny stub sketch (pio/libcheck.cpp)
that proves the portable core library compiles for the ESP32-S3. Run from the repository root: python3 tools/gen_pio_ini.py"""
import os
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
S3 = """[env:esp32s3]
platform = espressif32@6.9.0              ; Arduino-ESP32 2.0.17 (same core as tools/esp32_build.sh)
board = esp32-s3-devkitc-1                ; ESP32-S3-WROOM-1-N8 on the project PCB
framework = arduino
board_upload.flash_size = 8MB
board_build.partitions = default_8MB.csv
monitor_speed = 115200
build_src_filter = -<*> {src}
build_flags = -Ilib -Isrc {extra}-DARDUINO_USB_CDC_ON_BOOT=1 -DARDUINO_USB_MODE=1 -Wall -Wextra -Wno-unused-parameter -Wno-missing-field-initializers
{deps}"""
PROJECTS = [  # folder, title, kind, lib_deps, extra include dirs
    ("kinetic/firmware", "KINETIC motion controller", "app", [], ""),
    ("mitti-netra/firmware", "MITTI-NETRA soil + structure node", "app", ["paulstoffregen/OneWire@^2.3.8", "milesburton/DallasTemperature@^4.0.4"], ""),
    ("biotray/firmware", "BioTray vertical-farm controller", "app", ["paulstoffregen/OneWire@^2.3.8", "milesburton/DallasTemperature@^4.0.4", "knolleary/PubSubClient@^2.8", "claws/BH1750@^1.3.0"], "-Ipio "),
    ("aquaponics/firmware", "AQUAPONICS controller", "app", ["paulstoffregen/OneWire@^2.3.8", "milesburton/DallasTemperature@^4.0.4", "adafruit/Adafruit ADS1X15@^2.5.0"], ""),
    ("geotech/node", "GEONODE foundation-monitoring core library", "lib", [], ""),
    ("sorter/firmware", "SORTER tracking core library", "lib", [], ""),
    ("agrover/firmware", "AGROVER navigation core library", "lib", [], ""),
]
for folder, title, kind, deps, extra in PROJECTS:
    d = os.path.join(ROOT, folder)
    src = "+<src/*.cpp> +<lib/*.c>" if kind == "app" else "+<lib/*.c> +<pio/libcheck.cpp>"
    dep = ("lib_deps =\n" + "".join(f"    {x}\n" for x in deps)) if deps else ""
    head = (f"; {title} - PlatformIO workspace (generated by tools/gen_pio_ini.py)\n"
            f";   build: pio run        flash: pio run -t upload        monitor: pio device monitor\n"
            f";   host unit tests: make test (plain gcc, see Makefile)\n"
            + ("; library-only project: this builds the portable core for the ESP32-S3 with a stub sketch (pio/libcheck.cpp)\n" if kind == "lib" else "")
            + "\n[platformio]\nsrc_dir = .\ndefault_envs = esp32s3\n\n")
    open(os.path.join(d, "platformio.ini"), "w").write(head + S3.format(src=src, extra=extra, deps=dep))
    if kind == "lib" or extra:
        os.makedirs(os.path.join(d, "pio"), exist_ok=True)
    if kind == "lib":
        open(os.path.join(d, "pio", "libcheck.cpp"), "w").write("// PlatformIO compile check for the portable core library (no application yet)\n#include <Arduino.h>\nvoid setup() {}\nvoid loop() {}\n")
    if extra:   # BioTray: fall back to the committed example when the user has no src/secrets.h yet (a real src/secrets.h wins: same-folder include)
        open(os.path.join(d, "pio", "secrets.h"), "w").write("// Fallback for check builds only: copy src/secrets.h.example to src/secrets.h and edit it for a real device.\n#include \"../src/secrets.h.example\"\n")
    print("wrote", os.path.relpath(os.path.join(d, "platformio.ini"), ROOT))
