"""Finish a nearly routed board: freeze every track and via of a previous attempt as pre-route copper, then let the router add only the missing connections.
usage: complete.py <board> <routed out dir> [seed]  -> writes boards/<board>_done.py (spec = board + frozen copper) and builds it into out/<board>_done_s<seed>.
GND copper is not frozen: ground reaches pads through the pours and the stitching vias are placed again by the build."""
import sys, os, glob, subprocess
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import pcbnew
board, src = sys.argv[1], sys.argv[2]; seed = sys.argv[3] if len(sys.argv) > 3 else "1"
b = pcbnew.LoadBoard(glob.glob(os.path.join(src, "*.kicad_pcb"))[0]); mm = pcbnew.ToMM
pre, vias = [], []
for t in b.GetTracks():
    n = t.GetNetname()
    if not n or n == "GND": continue
    if t.GetClass() == "PCB_VIA": vias.append((n, round(mm(t.GetX()), 4), round(mm(t.GetY()), 4))); continue
    s, e = t.GetStart(), t.GetEnd()
    pre.append(dict(net=n, layer=0 if t.GetLayer() == pcbnew.F_Cu else 1, pts=[(round(mm(s.x), 4), round(mm(s.y), 4)), (round(mm(e.x), 4), round(mm(e.y), 4))], w=round(mm(t.GetWidth()), 3)))
open(os.path.join(HERE, "boards", f"{board}_done.py"), "w").write(
    f'"""{board} with the copper of {os.path.basename(src)} frozen (generated by complete.py)."""\nfrom .{board} import *\nfrom .{board} import BOARD as _B\n'
    f'BOARD = dict(_B, pre={pre!r}, pre_vias={vias!r})\n')
print("frozen", len(pre), "segments and", len(vias), "vias")
r = subprocess.run([sys.executable, os.path.join(HERE, "build.py"), f"{board}_done", "seed", seed], capture_output=True, text=True)
print(r.stdout[-400:], r.stderr[-800:])
