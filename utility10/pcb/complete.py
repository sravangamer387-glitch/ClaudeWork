"""Finish a nearly routed board: freeze every track and via of a previous attempt as pre-route copper, then let the router add only the missing connections.
usage: complete.py <board> <routed out dir> [seed] [radius_mm]  -> writes boards/<board>_done<seed>.py (spec = board + frozen copper) and builds it into out/<board>_done<seed>_s<seed>.
GND copper is not frozen: ground reaches pads through the pours and the stitching vias are placed again by the build."""
import sys, os, glob, subprocess
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import pcbnew
import json, math
board, src = sys.argv[1], sys.argv[2]; seed = sys.argv[3] if len(sys.argv) > 3 else "1"; rad = float(sys.argv[4]) if len(sys.argv) > 4 else 0.0
b = pcbnew.LoadBoard(glob.glob(os.path.join(src, "*.kicad_pcb"))[0]); mm = pcbnew.ToMM
# nets left free to re-route: the failed nets plus (radius > 0) every non-power net with copper within <radius> of a pad of a failed net
failed = {f[0] for f in json.load(open(os.path.join(src, "route_report.json")))["route_failures"]}
spots = [(mm(p.GetX()), mm(p.GetY())) for fp in b.GetFootprints() for p in fp.Pads() if p.GetNetname() in failed]
def near(t):
    pts = [(mm(t.GetX()), mm(t.GetY()))] if t.GetClass() == "PCB_VIA" else [(mm(t.GetStart().x) + (mm(t.GetEnd().x) - mm(t.GetStart().x)) * k / 8, mm(t.GetStart().y) + (mm(t.GetEnd().y) - mm(t.GetStart().y)) * k / 8) for k in range(9)]
    return any(math.hypot(x - sx, y - sy) < rad for (x, y) in pts for (sx, sy) in spots)
failed |= {x for x in os.environ.get("FREE", "").split(",") if x}   # FREE=net,..: also re-route nets that are split (e.g. a frozen stub not joined to the rest)
import importlib
_spec = importlib.import_module("boards." + board).BOARD
keep = {pr["net"] for pr in _spec.get("pre", [])} | set(_spec.get("supply", {}))      # never rip up hand pre-routes or supply rails
free = set(failed) | {t.GetNetname() for t in b.GetTracks() if rad > 0 and near(t) and not t.GetNetname().startswith("+") and t.GetNetname() not in keep}
print("left free:", sorted(free))
DROP = os.environ.get("DROP", "").split(",") if os.environ.get("DROP") else None   # DROP=x0,y0,x1,y1,net[,net]: drop those nets' segments with an end in the box (use only for leaf branches)
if DROP: DROP = [float(v) for v in DROP[:4]] + DROP[4:]
pre, vias, seen = [], [], set()
for t in b.GetTracks():
    n = t.GetNetname()
    if not n or n == "GND" or n in free: continue
    if t.GetClass() == "PCB_VIA":
        v = (n, round(mm(t.GetX()), 4), round(mm(t.GetY()), 4))
        if v not in seen: seen.add(v); vias.append(v)
        continue
    s, e = t.GetStart(), t.GetEnd()
    if DROP and n in DROP[4:] and any(DROP[0] <= mm(q.x) <= DROP[2] and DROP[1] <= mm(q.y) <= DROP[3] for q in (s, e)): continue   # local rip-up of a leaf branch
    key = (n, t.GetLayer(), frozenset([(round(mm(s.x), 4), round(mm(s.y), 4)), (round(mm(e.x), 4), round(mm(e.y), 4))]))
    if key in seen or s == e: continue
    seen.add(key)
    pre.append(dict(net=n, layer=0 if t.GetLayer() == pcbnew.F_Cu else 1, pts=[(round(mm(s.x), 4), round(mm(s.y), 4)), (round(mm(e.x), 4), round(mm(e.y), 4))], w=round(mm(t.GetWidth()), 3)))
open(os.path.join(HERE, "boards", f"{board}_done{seed}.py"), "w").write(
    f'"""{board} with the copper of {os.path.basename(src)} frozen (generated by complete.py)."""\nfrom .{board} import *\nfrom .{board} import BOARD as _B\n'
    f'BOARD = dict(_B, pre={pre!r}, pre_vias={vias!r})\n')
print("frozen", len(pre), "segments and", len(vias), "vias")
r = subprocess.run([sys.executable, os.path.join(HERE, "build.py"), f"{board}_done{seed}", "seed", seed], capture_output=True, text=True, env=dict(os.environ, BOOST=",".join(sorted(failed))))
print(r.stdout[-400:], r.stderr[-800:])
