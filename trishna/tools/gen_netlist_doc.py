#!/usr/bin/env python3
"""Generate docs/PINOUT_AND_NETLIST.md from the board definition (utility10/pcb/boards/trishna.py), so the pin map, the net list and
the BOM in the documentation can never drift from the PCB. usage: python3 gen_netlist_doc.py"""
import collections, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "utility10", "pcb"))
import importlib
mod = importlib.import_module("boards.trishna")
B = mod.BOARD; parts = B["parts"]
import lcsc_fill; lcsc_fill.fill(parts)

GPIO = {  # DevKitC socket pin -> ESP32 GPIO name
    "J4": {"1": "3V3", "2": "EN", "3": "GPIO36 (VP)", "4": "GPIO39 (VN)", "5": "GPIO34", "6": "GPIO35", "7": "GPIO32", "8": "GPIO33", "9": "GPIO25", "10": "GPIO26",
           "11": "GPIO27", "12": "GPIO14", "13": "GPIO12", "14": "GND", "15": "GPIO13", "16": "SD2", "17": "SD3", "18": "CMD", "19": "5V"},
    "J5": {"1": "GND", "2": "GPIO23", "3": "GPIO22", "4": "TXD0", "5": "RXD0", "6": "GPIO21", "7": "GND", "8": "GPIO19", "9": "GPIO18", "10": "GPIO5", "11": "GPIO17",
           "12": "GPIO16", "13": "GPIO4", "14": "GPIO0", "15": "GPIO2", "16": "GPIO15", "17": "SD1", "18": "SD0", "19": "CLK"}}
ROLE = {"EC_ADC": "ADC1_CH0: EC cell node (100 R / 1 nF)", "OPT_TX_ADC": "ADC1_CH3: transmission TIA out (1 k / 10 nF)", "OPT_SC_ADC": "ADC1_CH6: scatter TIA out (1 k / 10 nF)",
        "VIN_ADC": "ADC1_CH7: 12 V monitor, 100 k / 10 k (x11)", "SUMP_ADC": "ADC1_CH4: sump stream probe", "LEAK_ADC": "ADC1_CH5: chamber-B leak probe",
        "EC_DRV_A": "EC excitation A -> 330 R -> E1", "EC_DRV_B": "EC excitation B -> 100 R -> E2", "LVL_DRV": "pulse drive for sump + leak probes",
        "LED_BLU": "gate of Q2 (450 nm LED)", "PUMP_IN2": "DRV8871 IN2 (reverse / backwash), PWM 20 kHz", "PUMP_IN1": "DRV8871 IN1 (forward / sample), PWM 20 kHz",
        "SD_MOSI": "SPI MOSI -> microSD CMD", "SCL": "I2C SCL (VL53L1X), 4.7 k pull-up", "SDA": "I2C SDA (VL53L1X), 4.7 k pull-up", "SD_MISO": "SPI MISO <- microSD DAT0 (10 k pull-up)",
        "SD_SCK": "SPI SCK -> microSD CLK", "SD_CS": "SPI CS -> microSD DAT3 (10 k pull-up)", "TLM_TX": "UART2 TX -> J15 (telemetry out)", "TLM_RX": "UART2 RX <- J15",
        "ONEWIRE": "DS18B20 data, 4.7 k pull-up", "VALVE": "gate of Q1 (solenoid)", "LED_IR": "gate of Q3 (850 nm LED)", "DK3V3": "3.3 V from the buck via JP1", "GND": "ground"}

L = ["# TRISHNA controller: pinout, net list and BOM", "", f"Generated by `trishna/tools/gen_netlist_doc.py` from `utility10/pcb/boards/trishna.py` ({len(parts)} parts). "
     "Do not edit by hand: change the board file and regenerate.", "",
     "## 1. ESP32-DevKitC-32E pin mapping", "", "| Socket pin | DevKit label | Net | Function | Direction / notes |", "|---|---|---|---|---|"]
for ref in ("J4", "J5"):
    p = next(q for q in parts if q["ref"] == ref)
    for pin in sorted(GPIO[ref], key=int):
        net = p["nets"].get(pin, "not connected")
        g = GPIO[ref][pin]
        d = "input only (no pull-ups)" if g.startswith(("GPIO36", "GPIO39", "GPIO34", "GPIO35")) else ""
        if g in ("GPIO12", "GPIO2", "GPIO15", "GPIO5", "GPIO0"): d = (d + "; " if d else "") + "strapping pin: state at reset matters (see notes)"
        L.append(f"| {ref}.{pin} | {g} | {net} | {ROLE.get(net, '')} | {d} |")
L += ["", "Strapping pins: GPIO12 must be LOW at reset (3.3 V flash): DRV8871 IN2 has an internal pull-down. GPIO2 LOW at reset: 100 k gate pull-down on VALVE. "
      "GPIO15: 100 k pull-down on the LED_IR gate (only silences the boot log). GPIO5: 10 k pull-up (SD_CS idles high). GPIO0 is left free (BOOT button).", "",
      "## 2. Net list (every net, every connection)", "", "Copy-ready for KiCad / Altium: `net: REF.pin, REF.pin, ...`. The KiCad schematic, PCB and `.net` file in "
      "`utility10/pcb/release/trishna/3_design/` are the authoritative source.", "", "```"]
nets = collections.defaultdict(list)
for p in parts:
    for pin, n in p["nets"].items(): nets[n].append(f"{p['ref']}.{pin}")
for n in sorted(nets, key=lambda k: (k != "GND", k)):
    L.append(f"{n}: {', '.join(sorted(nets[n], key=lambda s: (s.split('.')[0], int(''.join(c for c in s.split('.')[1] if c.isdigit()) or 0))))}")
L += ["```", "", f"{len(nets)} nets.", "", "## 3. Bill of materials (board)", "", "| Refs | Qty | Value | Footprint | Manufacturer part | LCSC |", "|---|---|---|---|---|---|"]
g = collections.OrderedDict()
for p in parts:
    if p.get("tp"): continue
    k = (p["value"], p["fp"].split(":")[-1], p.get("mpn", ""), p.get("lcsc", ""))
    g.setdefault(k, []).append(p["ref"])
for (v, fp, mpn, lc), refs in g.items():
    L.append(f"| {', '.join(refs)} | {len(refs)} | {v} | {fp} | {mpn} | {lc} |")
L += ["", "Test points TP1-TP4 are bare pads (no part). Decoupling summary: VM bulk 2 x 100 uF/35 V electrolytic + 2 x 10 uF/50 V X5R + 100 nF at the DRV8871; "
      "buck output 2 x 22 uF X5R; DevKit 3V3 10 uF + 100 nF; analog rail 10 uF + 100 nF after the ferrite; MCP6002 100 nF; microSD 10 uF + 100 nF; every ADC input has its own RC.", ""]
# ---- consistency check: firmware pin map (board_pins.h) against the PCB nets ----
import re
FW = {"PIN_EC_ADC": "EC_ADC", "PIN_OPT_TX_ADC": "OPT_TX_ADC", "PIN_OPT_SC_ADC": "OPT_SC_ADC", "PIN_VIN_ADC": "VIN_ADC", "PIN_SUMP_ADC": "SUMP_ADC", "PIN_LEAK_ADC": "LEAK_ADC",
      "PIN_EC_DRV_A": "EC_DRV_A", "PIN_EC_DRV_B": "EC_DRV_B", "PIN_LVL_DRV": "LVL_DRV", "PIN_LED_BLU": "LED_BLU", "PIN_LED_IR": "LED_IR", "PIN_PUMP_IN1": "PUMP_IN1",
      "PIN_PUMP_IN2": "PUMP_IN2", "PIN_VALVE": "VALVE", "PIN_SDA": "SDA", "PIN_SCL": "SCL", "PIN_ONEWIRE": "ONEWIRE", "PIN_SD_SCK": "SD_SCK", "PIN_SD_MISO": "SD_MISO",
      "PIN_SD_MOSI": "SD_MOSI", "PIN_SD_CS": "SD_CS", "PIN_TLM_TX": "TLM_TX", "PIN_TLM_RX": "TLM_RX"}
hdr = open(os.path.join(ROOT, "trishna", "firmware", "src", "board_pins.h")).read()
gpio_of_net = {}
for ref in ("J4", "J5"):
    p = next(q for q in parts if q["ref"] == ref)
    for pin, n in p["nets"].items():
        m = re.match(r"GPIO(\d+)", GPIO[ref][pin])
        if m: gpio_of_net[n] = int(m.group(1))
bad = []
for macro, net in FW.items():
    m = re.search(r"#define\s+%s\s+(\d+)" % macro, hdr)
    if not m or gpio_of_net.get(net) != int(m.group(1)): bad.append(f"{macro}={m.group(1) if m else '?'} but PCB net {net} is on GPIO{gpio_of_net.get(net)}")
if bad: sys.exit("PIN MAP MISMATCH:\n  " + "\n  ".join(bad))
print("firmware pin map matches the PCB:", len(FW), "signals")
out = os.path.join(ROOT, "trishna", "docs", "PINOUT_AND_NETLIST.md"); os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("\n".join(L)); print("wrote", os.path.relpath(out, ROOT), len(nets), "nets", len(parts), "parts")
