"""Final sign-off table for every project: evidence pulled from the release folders (readiness), costing/REVIEW_findings.json, enclosure.json and confidence.json.
Status levels: APPROVED FOR PROTOTYPING (order a small first batch), APPROVED WITH CONDITIONS (prototype allowed; listed conditions apply), HOLD (do not order)."""
import os, json
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
REL = os.path.join(ROOT, "utility10", "pcb", "release")
CONF = json.load(open(os.path.join(ROOT, "costing", "confidence.json")))
FIND = json.load(open(os.path.join(ROOT, "costing", "REVIEW_findings.json"))) if os.path.exists(os.path.join(ROOT, "costing", "REVIEW_findings.json")) else {}
# conditions that are production gates (need a human, a lab or real-world data) rather than design defects
GATES = {
 "products/06-gas-suraksha": "not a certified gas detector: data-logging prototype only, never a safety device",
 "products/04-jal-rakshak": "12 V low-voltage prototype only; a mains version needs isolation design and certification",
 "jal-netra": "run the Gate 1 acoustic test before building more than 2 boards",
 "products/01-desi-games": "native-speaker language and fact review before the production print",
 "toys10/10-katha-cubes": "native-speaker review of Hindi/Telugu before the production print",
 "aquaponics": "water-only trial for a week; biological limits set with an aquaculture expert before fish",
 "biowatt": "bench-supply test first; one microbial fuel cell is marginal for cold start (use two in series)",
 "sorter": "machine guarding and an emergency stop before any powered test; vision model must be retrained on real produce",
 "agrover": "hardware emergency stop and a safety review before outdoor driving",
 "geotech": "thresholds must be re-derived from a real baseline recording before any alarm is trusted",
 "dj-setup": "built from bought equipment: follow the plan; mains equipment wiring by a qualified electrician",
 "trishna": "wellness prototype only (not a medical device); leak-test the printed flow cell and pass validation V1-V4 before real use; SG must be fitted to a refractometer",
 "electronics-toys/wave1": "check the MP3 command codes and the display-module polarity on the first board; toy-safety (IS 9873) testing before sale",
 "toys10/06-paper-rocket": "measure range and energy on the first unit; foam noses mandatory; toy-standard review before sale",
}
def board_state(board):
    p = os.path.join(REL, board or "", "5_verification", "readiness.json")
    if not board: return None
    if not os.path.exists(p): return "no release"
    r = json.load(open(p)); return "order-ready" if r.get("order_ready") else "NOT order-ready"
def enc_state(board, path=None):
    p = os.path.join(REL, board or "", "4_enclosure", "enclosure.json")
    if path and os.path.exists(os.path.join(ROOT, path, "mechanical", "out", "cad_report.json")): return f"custom CAD ({path}/mechanical)"
    if not board or not os.path.exists(p): return ""
    e = json.load(open(p))
    if e.get("version") != 2: return "old enclosure"
    if e.get("issues"): return f"enclosure issues: {len(e['issues'])}"
    return "plate for IP65 box" if e.get("mode", "").startswith("mounting plate") else ("box v2" + (f", {e['battery']} bay" if e.get("battery") else ""))
rows = []
for c in CONF:
    path, board = c["path"], c["board"]
    bs = board_state(board); es = enc_state(board, path); errs = [f for f in FIND.get(board or "", []) if f[0] == "error"]
    if bs == "NOT order-ready" or bs == "no release" or errs or c["order"] == "Low": status = "HOLD"
    elif path in GATES or c["works"] in ("Low", "Low-Medium"): status = "APPROVED WITH CONDITIONS"
    else: status = "APPROVED FOR PROTOTYPING"
    rows.append((c["group"], c["name"], status, bs or "no PCB", es, c["order"], c["works"], GATES.get(path, c["first"])))
L = ["# Final sign-off (prototype stage)", "", "Generated by `manuals/gen_signoff.py` from the release folders, the design review (`costing/REVIEW_findings.json`), the enclosure checks and `costing/CONFIDENCE.md`. "
     "**APPROVED FOR PROTOTYPING**: order a first small batch (5 boards / 1 kit). **APPROVED WITH CONDITIONS**: prototype allowed, the condition must be met before the step it names. **HOLD**: do not order.", "",
     "| Group | Project | Sign-off | PCB | Enclosure | Order conf. | Works conf. | Condition / first step |", "|---|---|---|---|---|---|---|---|"]
for r in rows: L.append("| " + " | ".join(r) + " |")
cnt = {k: sum(1 for r in rows if r[2] == k) for k in ("APPROVED FOR PROTOTYPING", "APPROVED WITH CONDITIONS", "HOLD")}
L += ["", "Totals: " + ", ".join(f"{k}: {v}" for k, v in cnt.items()), ""]
open(os.path.join(ROOT, "costing", "SIGNOFF.md"), "w").write("\n".join(L) + "\n"); print(cnt)
